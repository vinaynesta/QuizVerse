-- Challenge a friend: a shareable code for one finished exam quiz or mock. Friends' attempts at the same
-- quiz through the link point back at it. Deleting the creator's attempt deletes the challenge and leaves
-- the friends' attempts as ordinary history.
CREATE TABLE challenge (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(10) NOT NULL,
    attempt_id BIGINT      NOT NULL REFERENCES quiz_attempt (id) ON DELETE CASCADE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_challenge_code UNIQUE (code),
    CONSTRAINT uk_challenge_attempt UNIQUE (attempt_id)
);

ALTER TABLE quiz_attempt ADD COLUMN challenge_id BIGINT;
ALTER TABLE quiz_attempt ADD CONSTRAINT fk_attempt_challenge
    FOREIGN KEY (challenge_id) REFERENCES challenge (id) ON DELETE SET NULL;
CREATE INDEX idx_attempt_challenge ON quiz_attempt (challenge_id);
