-- Practice quizzes (revision, bookmarks, custom) have no exam/section, so the attempt records its kind.
-- For those, exam_id holds the kind and stage/section/level hold "practice".
ALTER TABLE quiz_attempt ADD COLUMN kind VARCHAR(16) DEFAULT 'exam' NOT NULL;

-- One row per question in a finished quiz. topic and subject are copied from the question bank
-- when the attempt is saved, so stats keep working if a question is later removed.
CREATE TABLE attempt_answer (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id  BIGINT      NOT NULL REFERENCES quiz_attempt (id) ON DELETE CASCADE,
    question_id VARCHAR(16) NOT NULL,
    subject     VARCHAR(32) NOT NULL,
    topic       VARCHAR(64) NOT NULL,
    chosen      INTEGER,
    correct     BOOLEAN     NOT NULL,
    seconds     INTEGER     NOT NULL
);
CREATE INDEX idx_answer_attempt ON attempt_answer (attempt_id);
CREATE INDEX idx_answer_question ON attempt_answer (question_id);
