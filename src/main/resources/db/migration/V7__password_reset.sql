-- Forgot password: one row per emailed reset link. Only a SHA-256 hash of the token is stored, so a database
-- leak can't be used to reset passwords. A link works once and for 30 minutes.
CREATE TABLE password_reset_token (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    used       BOOLEAN     NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_reset_token_hash UNIQUE (token_hash)
);
CREATE INDEX idx_reset_token_user ON password_reset_token (user_id);
