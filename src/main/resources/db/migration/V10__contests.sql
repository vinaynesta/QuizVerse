-- Live contests: a scheduled paper (an exam quiz or full mock from the catalog, by its key) that everyone sits
-- in the same window. Questions are served by the server in a per-entry shuffled order, and scored there.
CREATE TABLE contest (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title      VARCHAR(120) NOT NULL,
    quiz_key   VARCHAR(200) NOT NULL,
    starts_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    minutes    INTEGER      NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_contest_start ON contest (starts_at);

-- One row per registered user. started_at is set when the paper is first served; chosen holds the answers
-- (in the paper's original order, comma-separated, "-" for skipped) once submitted.
CREATE TABLE contest_entry (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contest_id    BIGINT NOT NULL REFERENCES contest (id) ON DELETE CASCADE,
    user_id       BIGINT NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    registered_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    started_at    TIMESTAMP(6) WITH TIME ZONE,
    submitted_at  TIMESTAMP(6) WITH TIME ZONE,
    chosen        VARCHAR(1500),
    score         DOUBLE PRECISION,
    correct       INTEGER,
    wrong         INTEGER,
    skipped       INTEGER,
    seconds_used  INTEGER,
    CONSTRAINT uk_contest_entry UNIQUE (contest_id, user_id)
);
CREATE INDEX idx_contest_entry_rank ON contest_entry (contest_id, score);
