-- Admin question editor (#32): a correction to one question, kept by its stable id. The question banks stay the
-- source of truth; scripts/build_exams.py applies the exported edits (scripts/question_edits.json) on the next
-- build, so a generator rerun can't silently undo a fix. "hidden" removes a question from practice pools.
CREATE TABLE question_edit (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id VARCHAR(16)   NOT NULL,
    question    VARCHAR(4000),
    options     VARCHAR(2000),
    answer      INTEGER,
    explanation VARCHAR(4000),
    hidden      BOOLEAN       NOT NULL,
    note        VARCHAR(500),
    edited_by   VARCHAR(50)   NOT NULL,
    updated_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_question_edit UNIQUE (question_id)
);
