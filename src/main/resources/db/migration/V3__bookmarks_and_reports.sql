CREATE TABLE bookmark (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    question_id VARCHAR(16) NOT NULL,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_bookmark_user_question UNIQUE (user_id, question_id)
);

-- Users flag questions with a wrong answer, a typo or unclear wording; admins review them.
CREATE TABLE question_report (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    question_id VARCHAR(16)  NOT NULL,
    reason      VARCHAR(32)  NOT NULL,
    note        VARCHAR(500),
    resolved    BOOLEAN      NOT NULL,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_report_open ON question_report (resolved, created_at);
